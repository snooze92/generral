    private static void AssertQuality(string title, string quality, bool proper)
    {
        var expected = (Quality)typeof(Quality).GetField(quality)!.GetValue(null)!;
        var result = QualityParser.ParseQuality(title);
        Assert.Multiple(() =>
        {
            Assert.That(result.Quality, Is.EqualTo(expected));
            Assert.That(result.Revision.Version, Is.EqualTo(proper ? 2 : 1));
        });
    }
