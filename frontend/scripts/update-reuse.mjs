#!/usr/bin/env node
// Regenerates the "Sonarr frontend code" annotation in REUSE.toml from scripts/sonarr-files.txt and
// the files marked "Adapted from Sonarr". --check fails if REUSE.toml is out of date.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { SONARR_REVISION } from './sonarr-revision.mjs';

const frontend = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const repo = path.dirname(frontend);
const reusePath = path.join(repo, 'REUSE.toml');

const begin = '# Sonarr frontend code:';
const end = 'SPDX-License-Identifier = "GPL-3.0-or-later"\n';

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    if (name === 'node_modules' || name === 'dist') {
      continue;
    }

    const full = path.join(dir, name);

    if (statSync(full).isDirectory()) {
      walk(full, out);
    } else if (/\.(tsx?|mjs|html|css)$/.test(name) && readFileSync(full, 'utf8').includes('Adapted from Sonarr')) {
      out.push(path.relative(repo, full));
    }
  }

  return out;
}

const vendored = readFileSync(path.join(frontend, 'scripts/sonarr-files.txt'), 'utf8')
  .split('\n')
  .map((line) => line.trim())
  .filter((line) => line && !line.startsWith('#'))
  .map((file) => `frontend/src/${file}`);

const extra = ['frontend/src/index.css', 'frontend/typings/element-class.ts', 'frontend/typings/jdu.d.ts', 'frontend/postcss.config.cjs'];
const paths = [...new Set([...vendored, ...extra, ...walk(frontend)])].sort();

const block = `${begin} files vendored by frontend/scripts/vendor-sonarr.mjs (list in
# frontend/scripts/sonarr-files.txt, Sonarr@${SONARR_REVISION}) and Generral files adapted from Sonarr
# (marked "Adapted from Sonarr"). Generated by: node frontend/scripts/update-reuse.mjs
[[annotations]]
path = [
${paths.map((p) => `  "${p}",`).join('\n')}
]
precedence = "aggregate"
SPDX-FileCopyrightText = "2010-2026 Sonarr Team and contributors"
${end}`;

const current = readFileSync(reusePath, 'utf8');
const start = current.indexOf(begin);
const stop = current.indexOf(end, start) + end.length;

if (start < 0) {
  throw new Error(`Marker "${begin}" not found in REUSE.toml`);
}

const updated = current.slice(0, start) + block + current.slice(stop);

if (process.argv.includes('--check')) {
  if (updated !== current) {
    console.error('REUSE.toml is out of date: run node frontend/scripts/update-reuse.mjs');
    process.exit(1);
  }

  console.log(`REUSE.toml lists ${paths.length} Sonarr-derived files`);
} else {
  writeFileSync(reusePath, updated);
  console.log(`Updated REUSE.toml (${paths.length} Sonarr-derived files)`);
}
